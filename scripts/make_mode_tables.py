#!/usr/bin/env python3
"""Generate src/dsp/ModeTables.hpp: partial frequency ratios and strike-position data for
PLINK's six objects (spec §5.5). Run once; the output is committed.

    python3 scripts/make_mode_tables.py      (needs numpy and scipy)
"""
import math
import os

import numpy as np
from scipy.optimize import brentq
from scipy.special import jn_zeros, jv

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 64
GRID = 128
MEMBRANE_ASPECT = 1.37
PLATE_ASPECT = 1.27


def beam_roots(n):
    """Roots of cos(b) cosh(b) = 1 (free-free bar), skipping the rigid-body zero root."""
    f = lambda b: math.cos(b) * math.cosh(b) - 1.0
    out = []
    for k in range(1, n + 1):
        guess = (2 * k + 1) * math.pi / 2
        if k <= 6:
            out.append(brentq(f, guess - 0.5, guess + 0.5))
        else:
            out.append(guess)
    return out


def string_modes():
    return [float(k) for k in range(1, N + 1)]


def beam_modes():
    b = beam_roots(N)
    return [(x / b[0]) ** 2 for x in b]


def marimba_modes():
    beam = beam_modes()
    r = [1.0, 4.0, 10.0]
    scale = 10.0 / beam[2] * 1.05
    for k in range(3, N):
        r.append(beam[k] * scale)
    return r


def drumhead_modes():
    z = []
    for m in range(0, 16):
        for n, j in enumerate(jn_zeros(m, 8), start=1):
            z.append((j, m, n))
    z.sort()
    z = z[:N]
    j01 = z[0][0]
    ratios = [j / j01 for j, _, _ in z]
    # weights on a radial grid: r from 0.92 (near the rim, Position 0) to 0 (centre, Position 127)
    w = []
    for j, m, n in z:
        row = []
        for g in range(GRID):
            p = g / (GRID - 1)
            r = 0.92 * (1.0 - p)
            row.append(abs(jv(m, j * r)))
        w.append(row)
    # normalise each mode's weights so its largest value is 1
    for row in w:
        mx = max(row) or 1.0
        for i in range(GRID):
            row[i] /= mx
    return ratios, w, [m for _, m, _ in z]


def rect_modes(aspect, plate):
    pairs = []
    for m in range(1, 13):
        for n in range(1, 13):
            if plate:
                f = (m / 1.0) ** 2 + (n / aspect) ** 2
            else:
                f = math.sqrt((m / 1.0) ** 2 + (n / aspect) ** 2)
            pairs.append((f, m, n))
    pairs.sort()
    pairs = pairs[:N]
    f0 = pairs[0][0]
    return [f / f0 for f, _, _ in pairs], [m for _, m, _ in pairs], [n for _, _, n in pairs]


def arr(name, vals, fmt="{:.6f}f", per=8, typ="float"):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("\t" + ", ".join(fmt.format(v) for v in vals[i:i + per]) + ",")
    return f"constexpr {typ} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    out = ["// Generated by scripts/make_mode_tables.py. Do not edit.",
           "// Partial frequency ratios (first = 1) for each PLINK object, spec §5.5.",
           "#pragma once", "", "namespace tx {", "",
           f"constexpr int MODE_N = {N};", f"constexpr int MODE_GRID = {GRID};", ""]
    out.append(arr("RATIO_STRING", string_modes()))
    out.append(arr("RATIO_BEAM", beam_modes()))
    out.append(arr("RATIO_MARIMBA", marimba_modes()))
    dr, dw, dm = drumhead_modes()
    out.append(arr("RATIO_DRUMHEAD", dr))
    flat = [v for row in dw for v in row]
    out.append(arr("WEIGHT_DRUMHEAD", flat, fmt="{:.4f}f", per=16))
    mr, mm, mn = rect_modes(MEMBRANE_ASPECT, False)
    out.append(arr("RATIO_MEMBRANE", mr))
    out.append(arr("MN_MEMBRANE_M", mm, fmt="{}", per=16, typ="unsigned char"))
    out.append(arr("MN_MEMBRANE_N", mn, fmt="{}", per=16, typ="unsigned char"))
    pr, pm, pn = rect_modes(PLATE_ASPECT, True)
    out.append(arr("RATIO_PLATE", pr))
    out.append(arr("MN_PLATE_M", pm, fmt="{}", per=16, typ="unsigned char"))
    out.append(arr("MN_PLATE_N", pn, fmt="{}", per=16, typ="unsigned char"))
    out.append("} // namespace tx\n")
    path = os.path.join(ROOT, "src", "dsp", "ModeTables.hpp")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print("wrote", path)
    print("beam", [round(x, 3) for x in beam_modes()[:6]])
    print("marimba", [round(x, 3) for x in marimba_modes()[:6]])
    print("drumhead", [round(x, 3) for x in dr[:8]])
    print("membrane", [round(x, 3) for x in mr[:6]])
    print("plate", [round(x, 3) for x in pr[:6]])


if __name__ == "__main__":
    main()
